// Liste des raisons de signalement (cohérent avec
// support_tickets.reason_key + lib/db/community.js VALID_REPORT_REASONS).
export const REPORT_REASONS = ['spam', 'inappropriate', 'harassment', 'plagiarism', 'wrong_info', 'other']

export function reportReasonLabel(t, key) {
  switch (key) {
    case 'spam':          return t.reasonSpam
    case 'inappropriate': return t.reasonInappropriate
    case 'harassment':    return t.reasonHarassment
    case 'plagiarism':    return t.reasonPlagiarism
    case 'wrong_info':    return t.reasonWrongInfo
    case 'other':         return t.reasonOther
    default:              return key
  }
}

// Ordre d'affichage des catégories dans les pills et la modale de
// composition. « general » en premier (catégorie par défaut, la plus
// large), puis les spécifiques.
export const CATEGORIES = ['general', 'tips', 'questions', 'pride', 'feedback']

export function categoryLabel(t, key) {
  switch (key) {
    case 'tips':      return t.catTips
    case 'questions': return t.catQuestions
    case 'pride':     return t.catPride
    case 'feedback':  return t.catFeedback
    case 'general':   return t.catGeneral
    default:          return key
  }
}

